_CITY_MAP = {c.lower(): (c, r) for c, r in CITIES}
_REGION_SET = {r.lower() for r in REGIONS}


def find_city(name: str) -> tuple[str, str] | None:
    """Точное совпадение города -> (город, регион)."""
    return _CITY_MAP.get(name.strip().lower())


def is_region(name: str) -> bool:
    return name.strip().lower() in _REGION_SET


def match_static(q: str, level: str, limit: int = 10) -> list[str]:
    """Подстрока по справочнику для suggest."""
    ql = q.strip().lower()
    if not ql:
        return []
    pool = REGIONS if level in ("region", "country") else None
    if level == "country":
        return [COUNTRY] if ql in COUNTRY.lower() else []
    if level == "region":
        return [r for r in REGIONS if ql in r.lower()][:limit]
    if level == "city":
        return [c for c, _ in CITIES if ql in c.lower()][:limit]
    return []
